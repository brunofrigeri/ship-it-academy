"""Builds src/course/deep-N.js from tools/deep/dayN.py.

Each dayN.py defines DAY (1-based) and LESSONS: a list with one list of blocks per lesson.
The blocks are appended to the end of that lesson's body when the course loads.
Run: python3 tools/deep/build.py
"""
import importlib.util, json, pathlib

written = []

root = pathlib.Path(__file__).resolve().parents[2]
for src in sorted((root / 'tools' / 'deep').glob('*.py')):
    if src.name == 'build.py': continue
    spec = importlib.util.spec_from_file_location(src.stem, src)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if hasattr(mod, 'EXTRAS'):  # extra topics, keyed by EXTRA id
        out = root / 'src' / 'course' / f'deep-{src.stem}.js'
        data = json.dumps(mod.EXTRAS, ensure_ascii=False, indent=1)
        out.write_text(
            f'/* Generated by tools/deep/build.py from {src.name}. Edit the .py file, not this one. */\n'
            f'(function () {{\n  var extra = {data};\n'
            f'  (window.EXTRA || []).forEach(function (e) {{ var b = extra[e.id]; if (!b) return; e.body = (e.body || []).concat(b); e.min = (e.min || 15) + 10; }});\n}})();\n'
        )
        written.append(out.name)
        print('wrote', out.relative_to(root), sum(len(v) for v in mod.EXTRAS.values()), 'blocks', len(mod.EXTRAS), 'topics')
        continue
    out = root / 'src' / 'course' / f'deep-{mod.DAY}.js'
    data = json.dumps(mod.LESSONS, ensure_ascii=False, indent=1)
    out.write_text(
        f'/* Generated by tools/deep/build.py from {src.name}. Edit the .py file, not this one. */\n'
        f'(function () {{\n  var day = (window.DAYS || []).find(function (d) {{ return d.n === {mod.DAY}; }});\n'
        f'  if (!day) return;\n  var extra = {data};\n'
        f'  extra.forEach(function (blocks, i) {{ var l = day.lessons[i]; if (!l) return; l.body = l.body.concat(blocks); if (l.min) l.min += 10; }});\n}})();\n'
    )
    written.append(out.name)
    print('wrote', out.relative_to(root), sum(len(l) for l in mod.LESSONS), 'blocks')

# one entry that loads every deep file (import it after the content and extras files)
(root / 'src' / 'course' / 'deep-all.js').write_text('// Generated by tools/deep/build.py\n' + ''.join(f"import './{n}';\n" for n in sorted(written)))
